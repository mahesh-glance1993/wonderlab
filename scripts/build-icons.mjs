// Builds every WonderLab app icon from one source design (brand/icon-source.svg), so iPad/iPhone, Android and the
// website always share the same mark. Run: node scripts/build-icons.mjs
//
// The mark: a cream laboratory flask with two "idea" bubbles (yellow + blue) on WonderLab green — simple silhouette,
// thick strokes, readable at 16 px. Outputs:
//   brand/icon-source.svg                 editable master (64-unit grid)
//   ios/…/AppIcon.appiconset/icon-1024.png  iOS / iPadOS (opaque, unmasked — iOS applies the squircle)
//   android mipmaps: ic_launcher.png (legacy, rounded), ic_launcher_foreground.png (adaptive, 108dp canvas, art inside
//   the 66dp safe zone), ic_launcher_monochrome.png (themed icons), background colour in values/colors.xml
//   public/: icon.svg, favicon-32.png, icon-192.png, icon-512.png, icon-maskable-512.png, apple-touch-icon.png
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const P = (p) => resolve(root, p);

// WonderLab green (the original app icon colour)
const INDIGO_TOP = '#3F6E58', INDIGO_BOTTOM = '#3F6E58', CREAM = '#FBF8F1', SUN = '#F4C95D', SKY = '#8ECAE6';

// flask + bubbles on a 64-unit grid (centred, art spans ~x 14–50, y 12–53)
const flask = (stroke, w = 4.2) => `
  <path d="M23.5 13h17M27 13v14.5L15.6 47.6a3.4 3.4 0 0 0 3 5.1h26.8a3.4 3.4 0 0 0 3-5.1L37 27.5V13"
        fill="none" stroke="${stroke}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
const liquid = `<path d="M21.3 38h21.4l5.3 9.6a2.2 2.2 0 0 1-1.9 3.3H17.9a2.2 2.2 0 0 1-1.9-3.3z" fill="${CREAM}" opacity="0.22"/>`;
const bubbles = (a = SUN, b = SKY) => `<circle cx="27.5" cy="43.5" r="3.3" fill="${a}"/><circle cx="36.8" cy="46" r="2.7" fill="${b}"/><circle cx="33" cy="35.5" r="1.6" fill="${b}" opacity="0.9"/>`;
const bg = (rx = 0) => `<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${INDIGO_TOP}"/><stop offset="1" stop-color="${INDIGO_BOTTOM}"/></linearGradient></defs>
  <rect width="64" height="64" rx="${rx}" fill="url(#g)"/>`;
const svg = (body, view = '0 0 64 64') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${view}">${body}</svg>`;

const master = svg(`${bg(14)}${liquid}${flask(CREAM)}${bubbles()}`);
const fullSquare = svg(`${bg(0)}${liquid}${flask(CREAM)}${bubbles()}`); // iOS masks it itself
// Android adaptive: 108-unit canvas, art scaled into the 66-unit safe zone (centre 54)
const adaptive = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><g transform="translate(54 54) scale(1.3) translate(-32 -33)">${body}</g></svg>`;
const fg = adaptive(`${liquid}${flask(CREAM)}${bubbles()}`);
const mono = adaptive(`${flask('#FFFFFF')}${bubbles('#FFFFFF', '#FFFFFF')}`);
const maskable = svg(`${bg(0)}<g transform="translate(32 32) scale(0.8) translate(-32 -33)">${liquid}${flask(CREAM)}${bubbles()}</g>`);

const out = async (svgText, size, file) => {
  mkdirSync(dirname(P(file)), { recursive: true });
  await sharp(Buffer.from(svgText), { density: Math.max(72, (size / 64) * 72 * 1.5) }).resize(size, size).png({ compressionLevel: 9 }).toFile(P(file));
};

mkdirSync(P('brand'), { recursive: true });
writeFileSync(P('brand/icon-source.svg'), master);
writeFileSync(P('brand/icon-android-foreground.svg'), fg);
writeFileSync(P('brand/icon-android-monochrome.svg'), mono);
writeFileSync(P('public/icon.svg'), master);

// iOS / iPadOS (single 1024 universal icon; must be opaque)
await sharp(Buffer.from(fullSquare), { density: 1200 }).resize(1024, 1024).flatten({ background: INDIGO_BOTTOM }).png().toFile(P('ios/iosApp/Assets.xcassets/AppIcon.appiconset/icon-1024.png'));

// Android
const dens = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [d, k] of Object.entries(dens)) {
  const res = `android/app/src/main/res/mipmap-${d}`;
  await out(master, Math.round(48 * k), `${res}/ic_launcher.png`);
  await out(fg, Math.round(108 * k), `${res}/ic_launcher_foreground.png`);
  await out(mono, Math.round(108 * k), `${res}/ic_launcher_monochrome.png`);
}
writeFileSync(P('android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-icons.mjs -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`);
mkdirSync(P('android/app/src/main/res/drawable'), { recursive: true });
writeFileSync(P('android/app/src/main/res/drawable/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-icons.mjs: WonderLab green -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:startColor="${INDIGO_TOP}" android:endColor="${INDIGO_BOTTOM}" />
</shape>
`);

// Website
await out(master, 32, 'public/favicon-32.png');
await out(master, 192, 'public/icon-192.png');
await out(master, 512, 'public/icon-512.png');
await out(maskable, 512, 'public/icon-maskable-512.png');
await sharp(Buffer.from(fullSquare), { density: 600 }).resize(180, 180).flatten({ background: INDIGO_BOTTOM }).png().toFile(P('public/apple-touch-icon.png'));

// previews for review: masks and small sizes
const prev = 'brand/preview';
mkdirSync(P(prev), { recursive: true });
for (const s of [16, 32, 48, 120]) await out(master, s, `${prev}/master-${s}.png`);
await out(svg(`<defs><clipPath id="c"><circle cx="54" cy="54" r="54"/></clipPath></defs><g clip-path="url(#c)"><rect width="108" height="108" fill="${INDIGO_BOTTOM}"/>${fg.replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g>`, '0 0 108 108').replace('viewBox="0 0 64 64"', ''), 216, `${prev}/android-circle.png`);
console.log('icons built');
