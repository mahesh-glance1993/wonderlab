/** [प्रश्न, सही उत्तर, गलत विकल्प, संकेत, कारण] */
type MQ = [q: string, a: string, w: string[], hint: string, why: string];
const mcq = (key: string, hint0: string, bank: MQ[], d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const [q, a, w, h1, why] = r.pick(bank);
  return {
    type: 'mcq', prompt: q, ...choose(r, a, r.shuffle(w)), hints: [hint0, h1, ELIM],
    mistakes: [{ when: 'wrong', explain: `यह सही नहीं है। ${why}` }],
    solution: [`सही उत्तर: ${a}`, why],
  };
}, d);

const matchT = (key: string, lead: string, pool: [string, string][], hints: string[], d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const pairs = r.shuffle(pool).slice(0, 4);
  const m = matching(r, pairs);
  return {
    type: 'match', prompt: `${lead}: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
    hints: [...hints, 'जो जोड़ा पक्का पता है, उसे पहले मिलाइए (match the pair you are sure of first).'],
    mistakes: [{ when: 'wrong', explain: 'कम से कम एक जोड़ा गलत है। बाएँ के हर शब्द को एक-एक करके जाँचिए।' }],
    solution: pairs.map(([a, b]) => `${a} → ${b}`),
  };
}, d);

const orderT = (key: string, prompt: string, steps: string[], hints: string[], why: string, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => ({
  type: 'order', prompt, ...ordering(r, steps), hints: [...hints, 'पहले और आखिरी काम को पहले पहचानिए (find the first and last step first).'],
  mistakes: [{ when: 'wrong', explain: `क्रम अभी ठीक नहीं है। ${why}` }],
  solution: [...steps.map((s, i) => `${i + 1}. ${s}`), why],
}), d);

