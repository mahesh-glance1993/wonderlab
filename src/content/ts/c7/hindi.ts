/** [शब्द, हिंदी अर्थ, English gloss] */
type W = [word: string, meaning: string, gloss: string];
interface LSpec {
  n: number; topic: string; title: string; note?: string;
  about: { title: string; intro: Block[]; examples: ExSpec[]; qa: MQ[]; order: { prompt: string; steps: string[]; why: string } };
  words: W[]; // >= 6
  ants: [string, string][]; // >= 5
  gram: { key: string; title: string; intro: Block[]; examples: ExSpec[]; qa: MQ[]; pairs: [string, string][]; lead: string; hints: string[] };
}

function vocab(id: string, lesson: string, words: W[], ants: [string, string][]): OSpec {
  const [w1, m1, g1] = words[0];
  const [a1, b1] = ants[0];
  return {
    id, title: `${lesson}: शब्द-भंडार (अर्थ, विलोम शब्द)`,
    intro: [
      h('पाठ से जुड़े शब्द (word bank)'),
      p('हर शब्द को उसके अर्थ और अंग्रेज़ी संकेत के साथ पढ़िए। फिर उस शब्द से अपना एक छोटा वाक्य बोलिए।'),
      ...words.map(([w, m, g]) => def(w, `${m} (${g})`)),
      h('विलोम शब्द (opposites)'),
      keys(...ants.map(([a, b]) => `${a} × ${b}`)),
      tip('नया शब्द याद करने का तरीका: शब्द → अर्थ → तेलुगु में समान शब्द → अपना वाक्य।'),
    ],
    examples: [
      ex(`‘${w1}’ शब्द का अर्थ बताइए।`, [`शब्द: ${w1}`, `अर्थ: ${m1} (${g1})`, `वाक्य में ‘${w1}’ की जगह ‘${m1}’ रखकर पढ़िए — अर्थ वही रहता है।`], `${w1} = ${m1}`),
      ex(`‘${a1}’ का विलोम शब्द लिखिए।`, ['विलोम = उल्टा अर्थ देने वाला शब्द।', `‘${a1}’ का उल्टा भाव: ‘${b1}’।`, `जोड़ी बोलिए: ${a1} × ${b1}।`], `${a1} × ${b1}`),
    ],
    practice: [
      tp('arth', (r) => {
        const [w, m, g] = r.pick(words);
        const wrong = r.shuffle(words.filter((x) => x[1] !== m)).slice(0, 3).map((x) => x[1]);
        return {
          type: 'mcq', prompt: `‘${w}’ शब्द का सही अर्थ चुनिए।`, ...choose(r, m, wrong),
          hints: ['हर अर्थ को शब्द की जगह वाक्य में रखकर देखिए।', `English clue: ${g}`, ELIM],
          mistakes: [{ when: 'wrong', explain: `‘${w}’ का अर्थ है ‘${m}’ (${g})।` }],
          solution: [`${w} = ${m} (${g})`],
        };
      }),
      tp('milan', (r) => {
        const pairs = r.shuffle(words).slice(0, 4);
        const m = matching(r, pairs.map(([w, mm]) => [w, mm] as [string, string]));
        return {
          type: 'match', prompt: `शब्द और अर्थ मिलाइए: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
          hints: ['जो जोड़ा पक्का पता है, उसे पहले मिलाइए।', `English clues: ${pairs.map((x) => `${x[0]} = ${x[2]}`).join('; ')}`],
          mistakes: [{ when: 'wrong', explain: 'कम से कम एक जोड़ा गलत है। हर अर्थ को वाक्य में रखकर जाँचिए।' }],
          solution: pairs.map(([w, mm, g]) => `${w} → ${mm} (${g})`),
        };
      }),
      tp('vilom', (r) => {
        const [a, b] = r.pick(ants);
        const wrong = r.shuffle(ants.filter((x) => x[1] !== b && x[0] !== a)).slice(0, 3).map((x) => x[1]);
        return {
          type: 'mcq', prompt: `‘${a}’ का विलोम शब्द (opposite) चुनिए।`, ...choose(r, b, wrong),
          hints: ['विलोम शब्द उल्टा अर्थ देता है।', `जोड़ी बोलकर देखिए: ${a} × ?`, ELIM],
          mistakes: [{ when: 'wrong', explain: `‘${a}’ का विलोम ‘${b}’ है। बाकी शब्द दूसरे शब्दों के विलोम हैं।` }],
          solution: [`${a} × ${b}`],
        };
      }),
    ],
  };
}

function lesson(s: LSpec): USpec {
  const base = `ts7.hi.${s.topic}`;
  const g = s.gram;
  return {
    id: `ts7.hi.ch${s.n}`, subject: 'hindi', title: `पाठ ${s.n} — ${s.title}`, source: src(s.n),
    note: s.note ? `${CHOSEN} ${s.note}` : CHOSEN,
    objectives: [
      {
        id: `${base}.path`, title: s.about.title, intro: s.about.intro, examples: s.about.examples,
        practice: [
          mcq('bodh', 'पाठ-परिचय फिर से पढ़िए: विधा (genre), विषय, सीख।', s.about.qa),
          orderT('kram', s.about.order.prompt, s.about.order.steps, ['क्या पहले हुआ, क्या बाद में — सोचिए।'], s.about.order.why),
        ],
      },
      vocab(`${base}.shabd`, s.title.split(' (')[0], s.words, s.ants),
      {
        id: `${base}.${g.key}`, title: g.title, intro: g.intro, examples: g.examples,
        practice: [
          mcq('pahchan', g.hints[0], g.qa, 2),
          matchT('milan', g.lead, g.pairs, g.hints, 2),
        ],
      },
    ],
  };
}

