/** [పదం, అర్థం, English gloss] */
type W = [word: string, meaning: string, gloss: string];
interface LSpec {
  n: number | string; topic: string; title: string; note?: string;
  about: { title: string; intro: Block[]; examples: ExSpec[]; qa: MQ[]; order: { prompt: string; steps: string[]; why: string } };
  words: W[]; // >= 6
  ants: [string, string][]; // >= 5
  gram: { key: string; title: string; intro: Block[]; examples: ExSpec[]; qa: MQ[]; pairs: [string, string][]; lead: string; hints: string[] };
}

function vocab(id: string, lesson: string, words: W[], ants: [string, string][]): OSpec {
  const [w1, m1, g1] = words[0];
  const [a1, b1] = ants[0];
  return {
    id, title: `${lesson}: పదజాలం (అర్థాలు, వ్యతిరేక పదాలు)`,
    intro: [
      h('పాఠానికి సంబంధించిన ముఖ్య పదాలు (key words)'),
      p('ప్రతి పదాన్ని, దాని అర్థాన్ని చదవండి. తర్వాత ఆ పదంతో మీ సొంత వాక్యం ఒకటి చెప్పండి.'),
      ...words.map(([w, m, g]) => def(w, `${m} (${g})`)),
      h('వ్యతిరేక పదాలు (opposites)'),
      keys(...ants.map(([a, b]) => `${a} × ${b}`)),
      tip('కొత్త పదం నేర్చుకోవడానికి మంచి మార్గం: పదం → అర్థం → మీ సొంత వాక్యం. ఇంట్లో వాళ్ళకు ఆ వాక్యం చెప్పండి.'),
    ],
    examples: [
      ex(`"${w1}" అనే పదానికి అర్థం చెప్పి, వాక్యంలో వాడండి.`, [`పదం: ${w1}`, `అర్థం: ${m1} (${g1})`, `వాక్యంలో "${w1}" స్థానంలో "${m1}" పెట్టి చదివితే భావం మారదు — అదే సరైన అర్థం అని తెలుసుకోవచ్చు.`], `${w1} = ${m1}`),
      ex(`"${a1}" అనే పదానికి వ్యతిరేక పదం రాయండి.`, ['వ్యతిరేక పదం అంటే పూర్తిగా విరుద్ధమైన (opposite) అర్థం ఇచ్చే పదం.', `"${a1}" కు విరుద్ధమైన భావం: "${b1}".`, `రెండింటినీ కలిపి చదవండి: ${a1} × ${b1} — భావాలు ఎదురెదురుగా ఉన్నాయి.`], `${a1} × ${b1}`),
    ],
    practice: [
      tp('artham', (r) => {
        const [w, m, g] = r.pick(words);
        const wrong = r.shuffle(words.filter((x) => x[1] !== m)).slice(0, 3).map((x) => x[1]);
        return {
          type: 'mcq', prompt: `"${w}" అనే పదానికి సరైన అర్థం ఏది?`, ...choose(r, m, wrong),
          hints: ['ప్రతి అర్థాన్ని ఆ పదం స్థానంలో ఒక వాక్యంలో పెట్టి చూడండి.', `English clue: ${g}`, ELIM],
          mistakes: [{ when: 'wrong', explain: `"${w}" అంటే "${m}" (${g}).` }],
          solution: [`${w} = ${m} (${g})`],
        };
      }),
      tp('jatha', (r) => {
        const pairs = r.shuffle(words).slice(0, 4);
        const m = matching(r, pairs.map(([w, mm]) => [w, mm] as [string, string]));
        return {
          type: 'match', prompt: `పదాలను వాటి అర్థాలతో జతపరచండి: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
          hints: ['ఖచ్చితంగా తెలిసిన జతను ముందు కలపండి.', `English clues: ${pairs.map((x) => `${x[0]} = ${x[2]}`).join('; ')}`],
          mistakes: [{ when: 'wrong', explain: 'కనీసం ఒక జత తప్పు. ప్రతి అర్థాన్ని వాక్యంలో పెట్టి సరిచూడండి.' }],
          solution: pairs.map(([w, mm, g]) => `${w} → ${mm} (${g})`),
        };
      }),
      tp('vyati', (r) => {
        const [a, b] = r.pick(ants);
        const wrong = r.shuffle(ants.filter((x) => x[1] !== b && x[0] !== a)).slice(0, 3).map((x) => x[1]);
        return {
          type: 'mcq', prompt: `"${a}" అనే పదానికి వ్యతిరేక పదం (opposite) ఏది?`, ...choose(r, b, wrong),
          hints: ['వ్యతిరేక పదం పూర్తిగా విరుద్ధమైన అర్థాన్ని ఇస్తుంది.', `"${a} × ?" అని జంటగా చెప్పి చూడండి.`, ELIM],
          mistakes: [{ when: 'wrong', explain: `"${a}" కు వ్యతిరేక పదం "${b}". మిగిలినవి వేరే పదాలకు వ్యతిరేకాలు.` }],
          solution: [`${a} × ${b}`],
        };
      }),
    ],
  };
}

function lesson(s: LSpec): USpec {
  const base = `ts7.te.${s.topic}`;
  const g = s.gram;
  const no = typeof s.n === 'number' ? `పాఠం ${s.n}` : 'ఉపవాచకం';
  return {
    id: `ts7.te.ch${s.n}`, subject: 'telugu', title: `${no} — ${s.title}`, source: src(s.n),
    note: s.note ? `${CHOSEN} ${s.note}` : CHOSEN,
    objectives: [
      {
        id: `${base}.path`, title: s.about.title, intro: s.about.intro, examples: s.about.examples,
        practice: [
          mcq('avagahana', 'పాఠ పరిచయాన్ని మళ్ళీ చదవండి: ప్రక్రియ, రచయిత, ఇతివృత్తం (theme).', s.about.qa),
          orderT('kramam', s.about.order.prompt, s.about.order.steps, ['ఏది ముందు, ఏది తర్వాత అని ఆలోచించండి.'], s.about.order.why),
        ],
      },
      vocab(`${base}.padalu`, s.title.split(' (')[0], s.words, s.ants),
      {
        id: `${base}.${g.key}`, title: g.title, intro: g.intro, examples: g.examples,
        practice: [
          mcq('gurtimpu', g.hints[0], g.qa, 2),
          matchT('jatha', g.lead, g.pairs, g.hints, 2),
        ],
      },
    ],
  };
}

