/** [question, correct answer, wrong answers, hint, why the answer is right] */
type MQ = [string, string, string[], string, string];
const mcqT = (key: string, hint0: string, bank: MQ[], d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const [q, a, w, h1, why] = r.pick(bank);
  return {
    type: 'mcq', prompt: q, ...choose(r, a, r.shuffle(w)), hints: [hint0, h1, H3],
    mistakes: [{ when: 'wrong', explain: `సరికాదు. ${why}` }],
    solution: [`సరైన జవాబు: ${a}.`, why],
  };
}, d);

const matchT = (key: string, lead: string, pool: [string, string][], hints: string[], n = 4, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const pairs = r.shuffle(pool).slice(0, n);
  const m = matching(r, pairs);
  return {
    type: 'match', prompt: `${lead}: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
    hints: [...hints, 'ఖచ్చితంగా తెలిసిన జతలను ముందు కలపండి; మిగిలినవి తేలికవుతాయి.'],
    mistakes: [{ when: 'wrong', explain: 'కనీసం ఒక జత తప్పుగా ఉంది. ఎడమవైపు ప్రతి అంశాన్ని ఒక్కొక్కటిగా సరిచూడండి.' }],
    solution: pairs.map(([a, b]) => `${a} → ${b}`),
  };
}, d);

const tapT = (key: string, prompt: string, pool: [string, boolean][], hints: string[], why: string, n = 5, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const pick = r.shuffle(pool).slice(0, n);
  const yes = pool.find((x) => x[1])!, no = pool.find((x) => !x[1])!;
  if (!pick.some((x) => x[1])) pick[0] = yes;
  if (!pick.some((x) => !x[1])) pick[n - 1] = no;
  return {
    type: 'tap', prompt, ...tapAll(r, pick.map(([label, ok]) => ({ label, ok }))), hints: [...hints, H3],
    mistakes: [{ when: 'wrong', explain: `ప్రతి ఆప్షన్‌ను విడిగా పరిశీలించండి. ${why}` }],
    solution: [`సరైనవి: ${pick.filter((x) => x[1]).map((x) => x[0]).join(' ; ')}.`, why],
  };
}, d);

interface OB { prompt: string; steps: string[]; why: string }
const orderT = (key: string, bank: OB[], hints: string[], d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const b = r.pick(bank);
  return {
    type: 'order', prompt: b.prompt, ...ordering(r, b.steps), hints: [...hints, 'మొదటి అంశాన్ని, చివరి అంశాన్ని ముందుగా గుర్తించండి.'],
    mistakes: [{ when: 'wrong', explain: `క్రమం ఇంకా సరిగా లేదు. ${b.why}` }],
    solution: [...b.steps.map((s, i) => `${i + 1}. ${s}`), b.why],
  };
}, d);

