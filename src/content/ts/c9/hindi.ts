/** [प्रश्न, सही उत्तर, गलत विकल्प, संकेत, कारण] */
type MQ = [q: string, a: string, w: string[], hint: string, why: string];
const mcq = (key: string, hint0: string, bank: MQ[], d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const [q, a, w, h1, why] = r.pick(bank);
  return {
    type: 'mcq', prompt: q, ...choose(r, a, w), hints: [hint0, h1, ELIM],
    mistakes: [{ when: 'wrong', explain: `यह सही नहीं है। ${why}` }],
    solution: [`सही उत्तर: ${a}`, why],
  };
}, d);

const matchT = (key: string, what: string, pool: [string, string][], hints: string[], n = 4, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const pairs = r.shuffle(pool).slice(0, n);
  const m = matching(r, pairs);
  return {
    type: 'match', prompt: `${what} — सही जोड़े मिलाइए: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
    hints, mistakes: [{ when: 'wrong', explain: 'कम से कम एक जोड़ा गलत है। बाएँ के हर शब्द को एक-एक करके जाँचिए (check each pair one at a time).' }],
    solution: pairs.map(([a, b]) => `${a} → ${b}`),
  };
}, d);

/** One of several correct sequences is picked; the learner restores its order. */
const orderT = (key: string, prompt: string, seqs: string[][], hints: string[], why: string, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const steps = r.pick(seqs);
  return {
    type: 'order', prompt, ...ordering(r, steps), hints,
    mistakes: [{ when: 'wrong', explain: `क्रम अभी ठीक नहीं है। ${why}` }],
    solution: [...steps.map((s, i) => `${i + 1}. ${s}`), why],
  };
}, d);

const tapT = (key: string, prompt: string, pool: [string, boolean][], hints: string[], why: string, n = 5, d: 1 | 2 | 3 = 1): TSpec => tp(key, (r) => {
  const pick = r.shuffle(pool).slice(0, n);
  const yes = pool.find((x) => x[1])!, no = pool.find((x) => !x[1])!;
  if (!pick.some((x) => x[1])) pick[0] = yes;
  if (!pick.some((x) => !x[1])) pick[n - 1] = no;
  return {
    type: 'tap', prompt, ...tapAll(r, pick.map(([label, ok]) => ({ label, ok }))), hints,
    mistakes: [{ when: 'wrong', explain: `हर विकल्प को अलग से जाँचिए। ${why}` }],
    solution: [`सही: ${pick.filter((x) => x[1]).map((x) => x[0]).join(' / ')}`, why],
  };
}, d);

// ---------- शब्द-भंडार (vocabulary) objective builder ----------
/** [शब्द, हिंदी अर्थ, English gloss, उदाहरण-वाक्य?] */
type W = [word: string, meaning: string, gloss: string, sentence?: string];
interface VocabSpec {
  id: string; title: string; lesson: string;
  words: W[]; // >= 6
  ants: [string, string][]; // >= 5 विलोम pairs
  syn?: [string, string[]][]; // >= 5 entries, each with >= 2 पर्यायवाची
  idioms?: [string, string, string][]; // [मुहावरा, अर्थ, वाक्य] >= 5
  note?: string;
}
const vocab = (v: VocabSpec): OSpec => {
  const practice: TSpec[] = [
    tp('arth', (r) => {
      const [w, m, g] = r.pick(v.words);
      const wrong = r.shuffle(v.words.filter((x) => x[1] !== m)).slice(0, 3).map((x) => x[1]);
      return {
        type: 'mcq', prompt: `‘${v.lesson}’ — ‘${w}’ शब्द का सही अर्थ चुनिए।`, ...choose(r, m, wrong),
        hints: ['हर अर्थ को शब्द की जगह वाक्य में रखकर देखिए (substitute each meaning in a sentence).', `English clue: ${g}`, ELIM],
        mistakes: [{ when: 'wrong', explain: `‘${w}’ का अर्थ है ‘${m}’ (${g}).` }],
        solution: [`${w} = ${m} (${g})`],
      };
    }),
    tp('milan', (r) => {
      const pairs = r.shuffle(v.words).slice(0, 4);
      const m = matching(r, pairs.map(([w, mm]) => [w, mm] as [string, string]));
      return {
        type: 'match', prompt: `शब्द और अर्थ मिलाइए: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
        hints: ['जो जोड़ा पक्का पता है, उसे पहले मिलाइए (start with the pair you are sure of).', `English clues: ${pairs.map((x) => `${x[0]} = ${x[2]}`).join('; ')}`],
        mistakes: [{ when: 'wrong', explain: 'कम से कम एक जोड़ा गलत है। हर शब्द का अर्थ वाक्य में रखकर जाँचिए।' }],
        solution: pairs.map(([w, mm, g]) => `${w} → ${mm} (${g})`),
      };
    }),
    tp('vilom', (r) => {
      const [a, b] = r.pick(v.ants);
      const wrong = r.shuffle(v.ants.filter((x) => x[1] !== b && x[0] !== a)).slice(0, 3).map((x) => x[1]);
      return {
        type: 'mcq', prompt: `‘${a}’ का विलोम शब्द (opposite) चुनिए।`, ...choose(r, b, wrong),
        hints: ['विलोम शब्द ठीक उल्टा अर्थ देता है (an antonym gives the opposite meaning).', `‘${a}’ के उल्टे भाव के बारे में सोचिए — जोड़ी बनाकर बोलिए: ${a} – ?`, ELIM],
        mistakes: [{ when: 'wrong', explain: `‘${a}’ का विलोम ‘${b}’ है। बाकी शब्द दूसरे शब्दों के विलोम हैं।` }],
        solution: [`${a} × ${b}`],
      };
    }),
  ];
  if (v.syn) {
    const syn = v.syn;
    practice.push(tp('paryay', (r) => {
      const [w, ss] = r.pick(syn);
      const others = r.shuffle(syn.filter((x) => x[0] !== w).flatMap((x) => x[1])).slice(0, 3);
      const pool: [string, boolean][] = [...ss.slice(0, 3).map((s) => [s, true] as [string, boolean]), ...others.map((s) => [s, false] as [string, boolean])];
      return {
        type: 'tap', prompt: `‘${w}’ के सभी पर्यायवाची शब्द (synonyms) चुनिए।`, ...tapAll(r, pool.map(([label, ok]) => ({ label, ok }))),
        hints: ['पर्यायवाची शब्दों का अर्थ लगभग एक-सा होता है (same meaning, different words).', `‘${w}’ के एक से अधिक पर्यायवाची सही हैं।`],
        mistakes: [{ when: 'wrong', explain: `‘${w}’ के पर्यायवाची: ${ss.join(', ')}.` }],
        solution: [`${w} — ${ss.join(', ')}`],
      };
    }));
  }
  if (v.idioms) {
    const idi = v.idioms;
    practice.push(tp('muhavra', (r) => {
      const [m, a, s] = r.pick(idi);
      const wrong = r.shuffle(idi.filter((x) => x[0] !== m)).slice(0, 3).map((x) => x[1]);
      return {
        type: 'mcq', prompt: `मुहावरा ‘${m}’ का अर्थ चुनिए।`, ...choose(r, a, wrong),
        hints: ['मुहावरे का अर्थ शब्दों के सीधे अर्थ से अलग होता है (an idiom does not mean its literal words).', `प्रयोग देखिए: ${s}`, ELIM],
        mistakes: [{ when: 'wrong', explain: `‘${m}’ = ${a}. उदाहरण: ${s}` }],
        solution: [`${m} — ${a}`, `वाक्य: ${s}`],
      };
    }));
  }
  const withS = v.words.filter((w) => w[3]);
  const w1: W = withS[0] ?? v.words[0];
  const w2 = v.ants[0];
  const examples: ExSpec[] = [
    ex(`‘${w1[0]}’ का अर्थ बताइए और वाक्य में प्रयोग कीजिए।`, [`शब्द पहचानें: ${w1[0]}`, `अर्थ: ${w1[1]} (${w1[2]})`, w1[3] ? `वाक्य: ${w1[3]}` : `वाक्य: यह शब्द ‘${w1[1]}’ के भाव में आता है।`], `${w1[0]} = ${w1[1]}`),
    ex(`‘${w2[0]}’ का विलोम शब्द लिखिए।`, ['विलोम = उल्टा अर्थ देने वाला शब्द।', `‘${w2[0]}’ का उल्टा भाव: ‘${w2[1]}’`, `जाँच: ${w2[0]} और ${w2[1]} को साथ बोलिए — अर्थ उल्टे लगते हैं।`], `${w2[0]} × ${w2[1]}`),
  ];
  if (v.idioms) {
    const [m, a, s] = v.idioms[0];
    examples.push(ex(`मुहावरा ‘${m}’ का अर्थ लिखकर वाक्य बनाइए।`, ['मुहावरे का अर्थ शब्दशः नहीं, भाव से लिया जाता है।', `अर्थ: ${a}`, `वाक्य: ${s}`], `${m} — ${a}`));
  }
  const intro: Block[] = [
    h(`शब्द-भंडार: ${v.lesson} (word bank)`),
    p('नीचे पाठ से जुड़े कुछ कठिन शब्द हैं। हर शब्द को उसके हिंदी अर्थ और अंग्रेज़ी संकेत के साथ पढ़िए, फिर अपना वाक्य बनाइए।'),
    ...v.words.map(([w, m, g]) => def(w, `${m} (${g})`)),
    h('विलोम शब्द (opposites)'),
    keys(...v.ants.map(([a, b]) => `${a} × ${b}`)),
  ];
  if (v.syn) intro.push(h('पर्यायवाची शब्द (synonyms)'), keys(...v.syn.map(([w, ss]) => `${w} — ${ss.join(', ')}`)));
  if (v.idioms) intro.push(h('मुहावरे (idioms)'), ...v.idioms.map(([m, a, s]) => def(m, `${a} — ${s}`)));
  intro.push(tip('याद रखने का तरीका: हर नए शब्द से अपने घर या स्कूल के बारे में एक वाक्य बनाइए। तेलुगु में उसका समान शब्द भी सोचिए।'));
  if (v.note) intro.push(remember(v.note));
  return { id: v.id, title: v.title, intro, examples, practice };
};

