const info = (c: string) => INFO[c] ?? c;

// ---------- grammar objective builder: classify rows [item, category, detail?] ----------
type Row = [string, string, string?];
interface GSpec {
  id: string; title: string; intro: Block[]; examples: ExSpec[]; rows: Row[];
  ask: string; detAsk?: string; hints: [string, string]; extra?: TSpec[];
}
function gram(g: GSpec): OSpec {
  const cats = [...new Set(g.rows.map((x) => x[1]))];
  const hasDet = g.rows.every((x) => x[2]);
  const practice: TSpec[] = [
    tp('cls', (r) => {
      const [item, cat, det] = r.pick(g.rows);
      return {
        type: 'mcq', prompt: `"${item}" — ${g.ask}`, ...choose(r, cat, r.shuffle(cats.filter((c) => c !== cat))),
        hints: [g.hints[0], g.hints[1], `నియమం: ${info(cat)}`],
        mistakes: [{ when: 'wrong', explain: `సరికాదు. ${info(cat)}` }],
        solution: [`"${item}" → ${cat}.`, info(cat), ...(det ? [`వివరణ: ${det}`] : [])],
      };
    }),
    tp('tap', (r) => {
      const c = r.pick(cats);
      const yes = r.shuffle(g.rows.filter((x) => x[1] === c)).slice(0, 3);
      const no = r.shuffle(g.rows.filter((x) => x[1] !== c)).slice(0, Math.max(2, 5 - yes.length));
      const items = [...yes.map((x) => ({ label: x[0], ok: true })), ...no.map((x) => ({ label: x[0], ok: false }))];
      return {
        type: 'tap', prompt: `కింది వాటిలో "${c}" కు చెందినవి అన్నీ ఎంచుకోండి.`, ...tapAll(r, items),
        hints: [g.hints[0], `నియమం: ${info(c)}`, H3],
        mistakes: [{ when: 'wrong', explain: `ప్రతి ఆప్షన్‌ను నియమంతో పోల్చండి. ${info(c)}` }],
        solution: [`సరైనవి: ${yes.map((x) => x[0]).join(' ; ')}.`, ...no.map((x) => `${x[0]} → ${x[1]}`)],
      };
    }),
  ];
  if (hasDet && g.detAsk) {
    practice.push(tp('det', (r) => {
      const [item, cat, det] = r.pick(g.rows);
      return {
        type: 'mcq', prompt: `"${item}" — ${g.detAsk}`, ...choose(r, det!, r.shuffle(g.rows.filter((x) => x[0] !== item && x[2] !== det).map((x) => x[2]!))),
        hints: [g.hints[1], `ఇది ${cat}. ${info(cat)}`, H3],
        mistakes: [{ when: 'wrong', explain: `సరికాదు. "${item}" కు సరైనది: ${det}.` }],
        solution: [`${item} → ${det}`, info(cat)],
      };
    }));
  }
  if (cats.length >= 3) {
    practice.push(tp('match', (r) => {
      const cs = r.shuffle(cats).slice(0, 4);
      const pairs = cs.map((c) => [r.pick(g.rows.filter((x) => x[1] === c))[0], c] as [string, string]);
      const m = matching(r, pairs);
      return {
        type: 'match', prompt: `ప్రతి దానిని దాని రకంతో జతపరచండి: ${pairs.map((x) => x[0]).join(' · ')}`, left: m.left, right: m.right, answer: m.answer,
        hints: [g.hints[0], g.hints[1], 'ఖచ్చితంగా తెలిసిన జతను ముందు కలపండి.'],
        mistakes: [{ when: 'wrong', explain: 'కనీసం ఒక జత తప్పుగా ఉంది. ప్రతి అంశాన్ని నియమంతో సరిచూడండి.' }],
        solution: pairs.map(([a, b]) => `${a} → ${b}`),
      };
    }));
  }
  return { id: g.id, title: g.title, intro: g.intro, examples: g.examples, practice: [...practice, ...(g.extra ?? [])] };
}

