export type SKey = keyof typeof S;
export const fill = (s: string, vars?: Record<string, string | number>) => (vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s);

export function useS() {
  const { lang } = useApp();
  return useCallback((k: SKey, vars?: Record<string, string | number>) => {
    const e = S[k] as { en: string; te?: string };
    return fill(lang === 'te' && e.te ? e.te : e.en, vars);
  }, [lang]);
}
